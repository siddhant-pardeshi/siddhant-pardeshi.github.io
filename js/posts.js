/* ============================================================
   POSTS + GITHUB — "Building in public".
   LinkedIn: featured-order collection (featuredRank), independent
   latest-post selection. No figures or dates are ever invented —
   cards render only what the owner configured.
   GitHub: repo cards from content.repos; verified stats merge in
   from data/github-snapshot.json (generated by the scheduled
   workflow). No stats fetched = no stats shown.
   ============================================================ */

(function () {
  "use strict";

  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  function fmtDate(iso) {
    if (!iso) return "";
    var d = new Date(iso + (iso.length === 10 ? "T12:00:00" : ""));
    if (isNaN(d)) return "";
    return d.toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" });
  }

  /* ---------------- LinkedIn ---------------- */
  function initPosts() {
    var C = window.CONTENT;
    var cfg = C.postsConfig;
    var root = document.getElementById("posts-view");
    var spotlightRoot = document.getElementById("linkedin-spotlight");
    if (!root) return;

    var posts = (cfg.posts || []).filter(function (p) { return p && p.url && p.title; });
    var ranked = posts.slice().sort(function (a, b) {
      var ra = a.featuredRank == null ? 9999 : a.featuredRank;
      var rb = b.featuredRank == null ? 9999 : b.featuredRank;
      return ra - rb;
    });

    var tabsEl = root.querySelector(".posts-tabs");
    var listEl = root.querySelector(".posts-list");
    var emptyEl = root.querySelector(".posts-empty");
    var freshEl = root.querySelector(".posts-freshness");
    var mode = "popular";

    function cardFor(p, rank) {
      var meta = [];
      if (p.publishedAt) meta.push("<span>" + esc(fmtDate(p.publishedAt)) + "</span>");
      if (typeof p.reactions === "number" && p.measuredAt) meta.push("<span>" + esc(String(p.reactions)) + " reactions · snapshot " + esc(fmtDate(p.measuredAt)) + "</span>");
      var a = document.createElement("a");
      a.className = "post-card" + (rank === 1 ? " post-card--rank1" : "");
      a.href = p.url;
      a.target = "_blank";
      a.rel = "noopener";
      a.innerHTML = (rank === 1 ? '<span class="rank-pill">Most popular</span>' : rank != null ? '<span class="rank-pill">Featured #' + rank + "</span>" : "")
        + "<h4>" + esc(p.title) + "</h4>"
        + (p.excerpt ? "<p>" + esc(p.excerpt) + "</p>" : "")
        + '<div class="post-meta">' + meta.join("") + "</div>"
        + '<span class="read-cta">Read on LinkedIn ↗</span>';
      return a;
    }

    function render() {
      listEl.innerHTML = "";
      var ordered;
      if (mode === "latest") {
        ordered = posts.slice().filter(function (p) { return p.publishedAt; })
          .sort(function (a, b) { return new Date(b.publishedAt) - new Date(a.publishedAt); })
          .concat(posts.filter(function (p) { return !p.publishedAt; }));
      } else {
        ordered = ranked;
      }
      ordered.forEach(function (p, i) {
        var rank = mode === "popular" ? (p.featuredRank != null ? p.featuredRank : (ranked.indexOf(p) + 1)) : null;
        listEl.appendChild(cardFor(p, rank));
      });
    }

    if (posts.length >= 2) {
      tabsEl.hidden = false;
      tabsEl.querySelectorAll(".posts-tab").forEach(function (t) {
        t.addEventListener("click", function () {
          mode = t.dataset.mode;
          tabsEl.querySelectorAll(".posts-tab").forEach(function (x) { x.setAttribute("aria-pressed", x === t ? "true" : "false"); });
          render();
        });
      });
    } else if (tabsEl) {
      tabsEl.hidden = true;
    }

    if (posts.length) {
      emptyEl.hidden = true;
      render();
    } else {
      emptyEl.hidden = false;
    }

    if (freshEl) {
      var parts = [];
      if (cfg.postsUpdatedAt) parts.push("Posts updated " + esc(fmtDate(cfg.postsUpdatedAt)));
      else parts.push("Post collection curated by Siddhant");
      parts.push("· manually maintained — not a live feed");
      freshEl.textContent = parts.join(" ");
    }

    /* Spotlight: featured post if configured, else profile CTA */
    if (spotlightRoot) {
      var featured = null;
      if (cfg.featuredPostId) featured = posts.find(function (p) { return p.id === cfg.featuredPostId; });
      if (!featured && ranked.length) featured = ranked[0];
      var latest = null;
      if (cfg.latestPostId) latest = posts.find(function (p) { return p.id === cfg.latestPostId; });
      if (!latest) {
        var withDates = posts.filter(function (p) { return p.publishedAt; });
        if (withDates.length) latest = withDates.sort(function (a, b) { return new Date(b.publishedAt) - new Date(a.publishedAt); })[0];
      }

      var slot = spotlightRoot.querySelector(".spotlight__slot");
      if (featured && slot) {
        slot.innerHTML = (featured === latest ? '<span class="rank-pill" style="font-family:var(--font-display);font-size:0.68rem;font-weight:700;letter-spacing:0.1em;text-transform:uppercase;background:var(--violet);color:#fff;padding:0.18rem 0.55rem;border-radius:999px">Most popular · Latest</span>' : '<span class="rank-pill" style="font-family:var(--font-display);font-size:0.68rem;font-weight:700;letter-spacing:0.1em;text-transform:uppercase;background:var(--violet);color:#fff;padding:0.18rem 0.55rem;border-radius:999px">Most popular post</span>')
          + '<h3 class="spotlight__title">' + esc(featured.title) + "</h3>"
          + (featured.excerpt ? '<p class="spotlight__excerpt">' + esc(featured.excerpt) + "</p>" : "")
          + '<p class="spotlight__meta">' + (featured.publishedAt ? esc(fmtDate(featured.publishedAt)) + " · " : "") + "Read the full post on LinkedIn</p>"
          + '<div class="spotlight__actions"><a class="btn btn--lime" href="' + esc(featured.url) + '" target="_blank" rel="noopener">Read the post on LinkedIn <span class="ext">↗</span></a></div>';
      } else if (slot) {
        /* No verified authored posts yet — polished profile CTA, nothing invented */
        slot.innerHTML = '<h3 class="spotlight__title">Build logs, hackathon results &amp; project stories</h3>'
          + '<p class="spotlight__excerpt">Siddhant shares what he builds and what he learns along the way. The featured post lands here as soon as the collection is curated.</p>'
          + '<div class="spotlight__actions"><a class="btn btn--lime" href="' + esc(C.site.linkedin) + '" target="_blank" rel="noopener">Connect with me on LinkedIn <span class="ext">↗</span></a>'
          + '<a class="btn btn--ghost-light" href="' + esc(C.site.github) + '" target="_blank" rel="noopener">Explore my GitHub <span class="ext">↗</span></a></div>';
      }

      var latestSlot = spotlightRoot.querySelector(".spotlight__latest");
      if (latestSlot) {
        if (latest && latest !== featured) {
          latestSlot.innerHTML = '<p class="side-note">Latest post · ' + esc(fmtDate(latest.publishedAt)) + "</p>"
            + '<a class="btn btn--ghost-light" href="' + esc(latest.url) + '" target="_blank" rel="noopener">Latest LinkedIn post <span class="ext">↗</span></a>';
        } else if (latest && latest === featured) {
          latestSlot.innerHTML = '<p class="side-note">The most popular post is also the newest one.</p>'
            + '<a class="btn btn--ghost-light" href="' + esc(latest.url) + '" target="_blank" rel="noopener">Go to that post <span class="ext">↗</span></a>';
        } else {
          latestSlot.innerHTML = '<p class="side-note">A direct “Latest post” shortcut appears here once post URLs are curated.</p>'
            + '<a class="btn btn--ghost-light" href="' + esc(C.site.linkedin) + '" target="_blank" rel="noopener">Follow the activity on LinkedIn <span class="ext">↗</span></a>';
        }
      }
    }
  }

  /* ---------------- GitHub ---------------- */
  function initRepos() {
    var C = window.CONTENT;
    var root = document.getElementById("repos-view");
    if (!root) return;
    var listEl = root.querySelector(".repos-list");
    var noteEl = root.querySelector(".stat-refresh-note");
    var moreEl = root.querySelector(".more-repos");

    function drawRepos(snapshot) {
      listEl.innerHTML = "";
      C.repos.slice().sort(function (a, b) { return a.featuredRank - b.featuredRank; }).forEach(function (r) {
        var s = snapshot && snapshot.repos ? snapshot.repos[repoName(r.repositoryUrl)] : null;
        var card = document.createElement("article");
        card.className = "repo-card";
        card.innerHTML =
          '<div class="repo-card__head"><a class="repo-card__name" href="' + esc(r.repositoryUrl) + '" target="_blank" rel="noopener">' + esc(repoName(r.repositoryUrl)) + ' ↗</a>'
          + (s && typeof s.stars === "number" ? '<span class="chip">' + "★ " + esc(String(s.stars)) + (typeof s.forks === "number" ? " · ⑂ " + esc(String(s.forks)) : "") + "</span>" : "")
          + "</div>"
          + "<p>" + esc(r.description) + "</p>"
          + '<div class="repo-card__foot">'
          + (s && s.language ? '<span class="stat">' + esc(s.language) + "</span>" : "")
          + (s && s.pushedAt ? '<span class="stat">Updated ' + esc(new Date(s.pushedAt).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" })) + "</span>" : "")
          + '<a class="repo-case-link" href="#' + esc(r.projectId) + '">Read the case study →</a>'
          + "</div>";
        listEl.appendChild(card);
      });
      if (noteEl) {
        if (snapshot && snapshot.fetchedAt) {
          noteEl.textContent = "Repository stats fetched from the GitHub API on " + new Date(snapshot.fetchedAt).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" }) + " by the site's scheduled sync.";
        } else {
          noteEl.textContent = "Live repository stats appear here once the scheduled GitHub sync runs. Nothing is shown until it is verified.";
        }
      }
      if (moreEl && snapshot && snapshot.more && snapshot.more.length) {
        moreEl.hidden = false;
        var items = snapshot.more.slice(0, 6).map(function (m) {
          return '<a href="' + esc(m.url) + '" target="_blank" rel="noopener">' + esc(m.name) + "</a>";
        });
        moreEl.innerHTML = "More public repositories: " + items.join(" · ") + ' · <a href="' + esc(C.site.github) + '" target="_blank" rel="noopener">See all on GitHub ↗</a>';
      }
    }

    function repoName(url) {
      var parts = url.replace(/\/$/, "").split("/");
      return parts[parts.length - 1];
    }

    drawRepos(null);
    fetch("data/github-snapshot.json", { cache: "no-cache" })
      .then(function (r) { return r.ok ? r.json() : null; })
      .then(function (snap) { if (snap) drawRepos(snap); })
      .catch(function () { /* keep baseline; no fabrication */ });
  }

  window.PostsView = { initPosts: initPosts, initRepos: initRepos };
})();
